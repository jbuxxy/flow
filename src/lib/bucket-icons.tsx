export type BucketIconKey = keyof typeof BUCKET_ICONS;

export const BUCKET_ICON_KEYS = Object.keys(BUCKET_ICONS) as BucketIconKey[];

// Ordered keyword -> icon key lookup. First match wins, so put more specific
