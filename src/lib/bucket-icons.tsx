// The keyword key for a bucket name, or null when nothing matches (the
// signal ensureBucketIcons uses to decide a bucket needs an AI pick).
export function keywordIconKey(name: string): BucketIconKey | null {
  for (const [pattern, key] of RULES) {
    if (pattern.test(name)) return key;
  }
  return null;
}

function iconFromKey(key: string | null | undefined): LucideIcon | null {
  return key && key in BUCKET_ICONS ? BUCKET_ICONS[key as BucketIconKey] : null;
}

// Final render resolution: the stored AI pick wins, then the live keyword
// rules, then a plain Wallet so there's always something to draw.
export function bucketIconComponent(bucket: { name: string; icon?: string | null }): LucideIcon {
  return iconFromKey(bucket.icon) ?? iconFromKey(keywordIconKey(bucket.name)) ?? Wallet;
}
